"""
VHDL backend generator.

Given an ``IRGraph``, the generator:

1. Looks up one ``VHDLOperator`` handler per node in ``OPERATOR_REGISTRY``
   (``UnsupportedOperatorError`` for unknown op types).
2. Emits ``<graph>_skid.vhd`` (the shared output skid buffer) and one
   ``<graph>_<node>.vhd`` per node (entity + architecture with the
   constants baked in).
3. Emits ``<graph>_top.vhd``, a structural entity that instantiates every
   stage and wires their valid / ready / data streams following
   ``IRNode.input_names``.

Entity names are prefixed with the graph name so that several networks can
live in the same VHDL library.

Options
-------
pipeline
    Optional registers inside the linear and pool stages (see
    ``digitalify.operators.base.PIPELINE_STAGES``).
folding
    ``{node_name: (PE, SIMD)}``: fold those linear stages into matrix-vector
    units with PE x SIMD multipliers (see ``docs/dataflow_design.md``).
"""

from __future__ import annotations

from digitalify.exceptions import UnsupportedOperatorError, VHDLGenerationError
from digitalify.ir.graph import IRGraph
from digitalify.ir.node import IRNode
from digitalify.operators.base import VHDLOperator, normalize_pipeline, skid_buffer
from digitalify.operators.registry import OPERATOR_REGISTRY


class VHDLGenerator:
    """Converts an ``IRGraph`` into synthesisable VHDL-2008 source files."""

    def __init__(self, pipeline=None, folding=None):
        self.pipeline = normalize_pipeline(pipeline)
        self.folding = dict(folding or {})

    def generate(self, ir: IRGraph) -> dict[str, str]:
        """
        Returns
        -------
        dict[str, str]
            ``{filename: vhdl_source}`` in compilation order: the skid buffer,
            the stages, then ``<ir.name>_top.vhd``.
        """
        if not ir.nodes:
            raise VHDLGenerationError("IRGraph is empty — nothing to generate.")
        unknown = set(self.folding) - {n.name for n in ir.nodes if n.op_type == "linear"}
        if unknown:
            raise ValueError(f"folding names {sorted(unknown)}, which are not linear stages of "
                             f"'{ir.name}' ({[n.name for n in ir.nodes if n.op_type == 'linear']}).")

        handlers = {node.name: self._handler(node) for node in ir.nodes}
        files: dict[str, str] = {f"{ir.name}_skid.vhd": skid_buffer(ir.name)}
        for node in ir.nodes:
            files[f"{self.entity_name(ir, node)}.vhd"] = handlers[node.name].architecture(
                node, self.entity_name(ir, node)
            )
        files[f"{ir.name}_top.vhd"] = self._top_level(ir, handlers)
        return files

    @staticmethod
    def entity_name(ir: IRGraph, node: IRNode) -> str:
        return f"{ir.name}_{node.name}"

    def latency(self, ir: IRGraph) -> int:
        """Nominal clocks from the first input beat to the first output beat
        without stalls (each stage's core plus its skid buffer).  Stages
        that wait for a whole tensor count their input beats."""
        return sum(self._handler(n).node_latency(n) + 1 for n in ir.nodes)

    def _handler(self, node: IRNode) -> VHDLOperator:
        cls = OPERATOR_REGISTRY.get(node.op_type)
        if cls is None:
            raise UnsupportedOperatorError(op_type=node.op_type, node_name=node.name)
        return cls(self.pipeline, self.folding.get(node.name))

    def _top_level(self, ir: IRGraph, handlers: dict[str, VHDLOperator]) -> str:
        in_bits = ir.in_features * ir.input_dtype.bits
        out_bits = ir.out_features * ir.output_dtype.bits
        top = f"{ir.name}_top"

        src = (
            f"-- Top-level structural entity for '{ir.name}'\n"
            f"-- Input : stream {ir.input_stream} (H, W, C) of {ir.input_dtype}"
            f"  (real = q * {ir.input_scale:g}), one pixel per beat\n"
            f"-- Output: stream {ir.output_stream} (H, W, C) of {ir.output_dtype}\n"
            "-- Handshake: a beat moves when valid and ready are both '1' (AXI4-Stream rules)\n"
            + (f"-- Pipeline: {self.pipeline.describe()}\n" if self.pipeline else "")
            + "-- Stages:\n"
            + "".join(f"--   {n.name:<14} {n.op_type:<11} {handlers[n.name].describe(n)}\n"
                      for n in ir.nodes)
            + "-- Generated by digitalify\n\n"
            "library ieee;\n"
            "use ieee.std_logic_1164.all;\n"
            "use ieee.numeric_std.all;\n\n"
            f"entity {top} is\n"
            "    port (\n"
            "        clk       : in  std_logic;\n"
            "        rst       : in  std_logic;\n"
            "        in_valid  : in  std_logic;\n"
            "        in_ready  : out std_logic;\n"
            f"        in_data   : in  std_logic_vector({in_bits - 1} downto 0);\n"
            "        out_valid : out std_logic;\n"
            "        out_ready : in  std_logic;\n"
            f"        out_data  : out std_logic_vector({out_bits - 1} downto 0)\n"
            "    );\n"
            f"end entity {top};\n\n"
            f"architecture structural of {top} is\n\n"
            "    -- Component declarations\n"
        )
        for node in ir.nodes:
            src += handlers[node.name].component_declaration(node, self.entity_name(ir, node)) + "\n\n"

        src += "    -- Streams between stages\n"
        src += ("    signal top_in_valid, top_in_ready : std_logic;\n"
                f"    signal top_in_data : std_logic_vector({in_bits - 1} downto 0);\n")
        for node in ir.nodes:
            bits = node.out_features * node.output_dtype.bits
            src += (f"    signal {node.name}_valid, {node.name}_ready : std_logic;\n"
                    f"    signal {node.name}_data  : std_logic_vector({bits - 1} downto 0);\n")
        src += (
            "\nbegin\n\n"
            "    top_in_valid <= in_valid;\n"
            "    top_in_data  <= in_data;\n"
            "    in_ready     <= top_in_ready;\n\n"
        )

        known = {"__input__"}
        for node in ir.nodes:
            if len(node.input_names) != 1 or node.input_names[0] not in known:
                raise VHDLGenerationError(
                    f"Node '{node.name}' has inputs {node.input_names}; expected one earlier node."
                )
            prev = node.input_names[0]
            src += handlers[node.name].instantiation(
                node, self.entity_name(ir, node),
                "top_in" if prev == "__input__" else prev, node.name,
            ) + "\n\n"
            known.add(node.name)

        last = ir.nodes[-1].name
        src += (
            f"    out_valid <= {last}_valid;\n"
            f"    out_data  <= {last}_data;\n"
            f"    {last}_ready <= out_ready;\n\n"
            "end architecture structural;\n"
        )
        return src
