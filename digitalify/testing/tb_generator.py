"""
VHDL-2008 self-checking testbench generator.

The generated testbench:
  - Instantiates ``{ir.name}_top`` as the DUT
  - Embeds test vectors (inputs + expected outputs) as VHDL constants
  - Drives a clock and applies one input vector per pipeline pass
  - Waits exactly ``pipeline_depth`` clock cycles for the output to appear
  - Compares each output to the expected value and reports PASSED / FAILED
  - Prints a summary line ("TB SUMMARY: X passed, Y failed") parseable by
    the GHDL runner
  - Terminates the simulation cleanly (no ``--stop-time`` required)

Pipeline depth
--------------
Only ``linear`` / ``quantized_linear`` layers are registered (1 clock each).
``relu`` is fully combinational (0 clocks).  The total pipeline depth is
therefore the number of linear nodes in the IRGraph.
"""

from __future__ import annotations

import numpy as np

from digitalify.ir.graph import IRGraph
from digitalify.testing.reference import generate_test_vectors


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _pipeline_depth(ir: IRGraph) -> int:
    """Number of registered pipeline stages (= number of linear layers)."""
    return sum(
        1 for n in ir.nodes
        if n.op_type in ("linear", "quantized_linear")
    )


def _pack_int8_vector(values: np.ndarray, data_width: int) -> str:
    """
    Pack an int8 numpy array into a VHDL hex literal.

    Feature 0 maps to the least-significant byte of the std_logic_vector,
    which in VHDL x"..." notation is the rightmost (least significant) pair
    of hex digits.  We therefore reverse the byte order before joining.

    Example: features [-3, 5] (8-bit) → x"05FD"
      data_i(7  downto 0) = 0x05 = +5  = feature 0  ✓
      data_i(15 downto 8) = 0xFD = -3  = feature 1  ✓
    """
    as_unsigned = values.view(np.uint8)  # reinterpret two's complement
    hex_str = "".join(f"{b:02X}" for b in reversed(as_unsigned))
    return f'x"{hex_str}"'


def _pipeline_wait_vhdl(depth: int) -> str:
    """Return the VHDL snippet that waits for the pipeline to drain."""
    if depth <= 1:
        return "            -- Single pipeline stage: output ready at this point"
    extra = depth - 1
    return (
        f"            -- Wait for {extra} more pipeline stage(s)\n"
        f"            for k in 1 to {extra} loop\n"
        f"                wait until rising_edge(clk);\n"
        f"            end loop;"
    )


# ---------------------------------------------------------------------------
# Public entry point
# ---------------------------------------------------------------------------

def generate_testbench(
    ir: IRGraph,
    n_vectors: int = 8,
    data_width: int = 8,
    clk_period_ns: int = 10,
    seed: int = 42,
) -> tuple[str, str]:
    """
    Generate a self-checking VHDL testbench for *ir*.

    Parameters
    ----------
    ir : IRGraph
        The computation graph whose top-level entity will be instantiated.
    n_vectors : int
        Number of test vectors (first three are edge cases, rest random).
    data_width : int
        Activation bit-width (must match the VHDLGenerator setting).
    clk_period_ns : int
        Clock period in nanoseconds.
    seed : int
        RNG seed for random test vectors.

    Returns
    -------
    (tb_filename, tb_vhdl_source) : tuple[str, str]
        Ready to be written to disk and passed to the GHDL runner.
    """
    inputs, expected = generate_test_vectors(
        ir, n_vectors=n_vectors, data_width=data_width, seed=seed
    )

    in_features  = ir.input_shape[-1]
    out_features = ir.output_shape[-1]
    in_bits  = in_features  * data_width
    out_bits = out_features * data_width
    depth    = _pipeline_depth(ir)

    top_entity = f"{ir.name}_top"
    tb_entity  = f"tb_{ir.name}"
    tb_filename = f"{tb_entity}.vhd"

    # Format test-vector arrays
    in_lits  = [_pack_int8_vector(inputs[i],   data_width) for i in range(n_vectors)]
    out_lits = [_pack_int8_vector(expected[i], data_width) for i in range(n_vectors)]

    def _array_literal(lits: list[str]) -> str:
        joined = ",\n        ".join(lits)
        return f"(\n        {joined}\n    )"

    pipeline_wait = _pipeline_wait_vhdl(depth)

    source = f"""\
-- Self-checking testbench for {top_entity}
-- Generated by digitalify.testing.tb_generator
--
-- Network  : {ir.name}
-- Input    : {in_features} x INT{data_width}  ({in_bits} bits)
-- Output   : {out_features} x INT{data_width}  ({out_bits} bits)
-- Pipeline : {depth} clock cycle(s)
-- Vectors  : {n_vectors}  (seed={seed})
-- Clock    : {clk_period_ns} ns

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity {tb_entity} is
end entity {tb_entity};

architecture sim of {tb_entity} is

    -- ── Clock & control ────────────────────────────────────────────────────────
    constant CLK_PERIOD : time    := {clk_period_ns} ns;
    signal   clk        : std_logic := '0';
    signal   rst        : std_logic := '1';
    signal   sim_done   : boolean   := false;

    -- ── DUT interface ──────────────────────────────────────────────────────────
    signal valid_i : std_logic := '0';
    signal data_i  : std_logic_vector({in_bits  - 1} downto 0) := (others => '0');
    signal valid_o : std_logic;
    signal data_o  : std_logic_vector({out_bits - 1} downto 0);

    -- ── Test vectors ───────────────────────────────────────────────────────────
    constant NUM_TESTS : integer := {n_vectors};

    type input_array_t  is array(0 to NUM_TESTS - 1)
        of std_logic_vector({in_bits  - 1} downto 0);
    type output_array_t is array(0 to NUM_TESTS - 1)
        of std_logic_vector({out_bits - 1} downto 0);

    constant TEST_INPUTS : input_array_t := {_array_literal(in_lits)};

    constant EXPECTED_OUTPUTS : output_array_t := {_array_literal(out_lits)};

begin

    -- ── Clock generation (stops when sim_done is set) ─────────────────────────
    clk <= not clk after CLK_PERIOD / 2 when not sim_done else '0';

    -- ── DUT instantiation ──────────────────────────────────────────────────────
    dut : entity work.{top_entity}
        port map (
            clk     => clk,
            rst     => rst,
            valid_i => valid_i,
            data_i  => data_i,
            valid_o => valid_o,
            data_o  => data_o
        );

    -- ── Stimulus and checker ───────────────────────────────────────────────────
    stim : process
        variable n_pass : integer := 0;
        variable n_fail : integer := 0;
    begin

        -- ── Reset sequence ────────────────────────────────────────────────────
        rst     <= '1';
        valid_i <= '0';
        data_i  <= (others => '0');
        wait until rising_edge(clk);
        wait until rising_edge(clk);
        rst <= '0';
        wait until rising_edge(clk);

        -- ── Test loop ─────────────────────────────────────────────────────────
        for i in 0 to NUM_TESTS - 1 loop

            -- Drive input for exactly one clock cycle
            data_i  <= TEST_INPUTS(i);
            valid_i <= '1';
            wait until rising_edge(clk);   -- input sampled here
            valid_i <= '0';
            data_i  <= (others => '0');

{pipeline_wait}

            -- Small settle time after the last registered rising edge
            wait for 1 ns;

            -- Check handshake
            assert valid_o = '1'
                report "Test " & integer'image(i) & ": valid_o not asserted"
                severity error;

            -- Check data
            if data_o = EXPECTED_OUTPUTS(i) then
                report "Test " & integer'image(i) & ": PASSED"
                    severity note;
                n_pass := n_pass + 1;
            else
                report "Test " & integer'image(i)
                    & ": FAILED  got=" & to_hstring(data_o)
                    & "  expected=" & to_hstring(EXPECTED_OUTPUTS(i))
                    severity error;
                n_fail := n_fail + 1;
            end if;

            -- Idle cycle before the next vector
            wait until rising_edge(clk);

        end loop;

        -- ── Summary ───────────────────────────────────────────────────────────
        report "TB SUMMARY: " & integer'image(n_pass) & " passed, "
            & integer'image(n_fail) & " failed out of "
            & integer'image(NUM_TESTS) & " tests"
            severity note;

        if n_fail = 0 then
            report "TB: ALL TESTS PASSED" severity note;
        else
            report "TB: TESTS FAILED" severity failure;
        end if;

        -- Stop the clock and terminate
        sim_done <= true;
        wait;

    end process stim;

end architecture sim;
"""
    return tb_filename, source
